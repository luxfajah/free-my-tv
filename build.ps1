# Native Windows PowerShell Build Script for Free My TV
param([switch]$Generic)

$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $ScriptDir

$JavaHome = "C:\Program Files\Microsoft\jdk-17.0.21.21-hotspot"
$AndroidHome = "c:\Users\luxpi\Desktop\btv\android-sdk"
$BuildTools = "$AndroidHome\build-tools\34.0.0"
$AndroidJar = "$AndroidHome\platforms\android-34\android.jar"

$Javac = "$JavaHome\bin\javac.exe"
$Java = "$JavaHome\bin\java.exe"
$Keytool = "$JavaHome\bin\keytool.exe"
$Jar = "$JavaHome\bin\jar.exe"
$Aapt2 = "$BuildTools\aapt2.exe"
$Zipalign = "$BuildTools\zipalign.exe"
$D8Jar = "$BuildTools\lib\d8.jar"
$ApksignerJar = "$BuildTools\lib\apksigner.jar"

Write-Host "--- Iniciando Compilação do Free My TV ---" -ForegroundColor Cyan

# 1. Carregar config.properties
$props = @{}
if (Test-Path "config.properties") {
    Get-Content "config.properties" -Encoding UTF8 | ForEach-Object {
        $line = $_.Trim()
        if ($line -and -not $line.StartsWith("#") -and $line.Contains("=")) {
            $parts = $line.Split("=", 2)
            $props[$parts[0].Trim()] = $parts[1].Trim()
        }
    }
}

function Get-Prop($key, $defaultVal) {
    if ($props.ContainsKey($key)) { return $props[$key] }
    return $defaultVal
}

$tmdbKey = Get-Prop "tmdb_key" ""
$tmdbRegion = Get-Prop "tmdb_region" "BR"
$lat = Get-Prop "latitude" "-8.0476"
$lon = Get-Prop "longitude" "-34.8770"
$city = Get-Prop "city" "Recife"
$hideAnim = if ((Get-Prop "hide_animation" "false") -eq "true") { "true" } else { "false" }
$stremio = if ((Get-Prop "open_in_stremio" "false") -eq "true") { "true" } else { "false" }
$lang = Get-Prop "language" "pt"
$showCrypto = if ((Get-Prop "show_crypto" "true") -eq "true") { "true" } else { "false" }
$currency = Get-Prop "currency" "BRL"
$temp = Get-Prop "temperature" "C"
$theme = Get-Prop "theme" "dark"
$disableAssist = if ((Get-Prop "disable_assistant" "false") -eq "true") { "true" } else { "false" }
$screensaver = if ((Get-Prop "screensaver" "true") -eq "true") { "true" } else { "false" }
$hideServices = Get-Prop "hide_services" ""
$genericBool = if ($Generic) { "true" } else { "false" }

# 2. Criar diretórios de saída
if (Test-Path "out") { Remove-Item "out" -Recurse -Force }
New-Item -ItemType Directory -Path "out\gen\io\freemytv" -Force | Out-Null
New-Item -ItemType Directory -Path "out\classes" -Force | Out-Null
New-Item -ItemType Directory -Path "out\res\xml" -Force | Out-Null

# 3. Gerar Config.java
$configJava = @"
package io.freemytv;

/** Generated by build.ps1 from config.properties. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$tmdbKey";
    static final String WATCHMODE_KEY = "";
    static final String PLEX_URL = "";
    static final String PLEX_TOKEN = "";
    static final String TRAKT_CLIENT_ID = "";
    static final String TMDB_REGION = "$tmdbRegion";
    static final String LATITUDE = "$lat";
    static final String LONGITUDE = "$lon";
    static final String CITY = "$city";
    static final String LANGUAGE = "$lang";
    static final String CURRENCY = "$currency";
    static final String TEMPERATURE = "$temp";
    static final String HIDE_SERVICES = "$hideServices";
    static final String THEME = "$theme";
    static final String IMMICH_SERVER = "";
    static final boolean DISABLE_ASSISTANT = $disableAssist;
    static final boolean SHOW_CRYPTO = $showCrypto;
    static final boolean HIDE_ANIMATION = $hideAnim;
    static final boolean SCREENSAVER = $screensaver;
    static final boolean GENERIC = $genericBool;
    static final boolean OPEN_IN_STREMIO = $stremio;
}
"@
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText("$ScriptDir\out\gen\io\freemytv\Config.java", $configJava, $utf8NoBom)

# 4. Gerar network_security_config.xml
$netSec = @"
<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
</network-security-config>
"@
[System.IO.File]::WriteAllText("$ScriptDir\out\res\xml\network_security_config.xml", $netSec, $utf8NoBom)

Write-Host "Compilando recursos com aapt2..." -ForegroundColor Yellow
& $Aapt2 compile --dir app/res -o out/res.zip
& $Aapt2 compile --dir out/res -o out/res-gen.zip

Write-Host "Vinculando APK com aapt2 link..." -ForegroundColor Yellow
& $Aapt2 link -o out/base.apk -I $AndroidJar --manifest app/AndroidManifest.xml --java out/gen out/res.zip out/res-gen.zip --min-sdk-version 26 --target-sdk-version 33 -A app/assets -0 ttf

# Fix asset paths in zip if backslashes are present
$fixJava = @"
import java.nio.file.*;
import java.util.zip.*;

public class FixAssets {
    public static void main(String[] args) throws Exception {
        Path apk = Paths.get(args[0]);
        Path tmp = apk.resolveSibling(apk.getFileName() + ".fixed");
        int renamed = 0;
        try (ZipInputStream in = new ZipInputStream(Files.newInputStream(apk));
             ZipOutputStream out = new ZipOutputStream(Files.newOutputStream(tmp))) {
            for (ZipEntry e; (e = in.getNextEntry()) != null; ) {
                byte[] data = in.readAllBytes();
                String name = e.getName().replace('\\', '/');
                if (!name.equals(e.getName())) renamed++;
                ZipEntry n = new ZipEntry(name);
                if (e.getMethod() == ZipEntry.STORED) {
                    n.setMethod(ZipEntry.STORED);
                    n.setSize(data.length);
                    n.setCompressedSize(data.length);
                    CRC32 crc = new CRC32();
                    crc.update(data);
                    n.setCrc(crc.getValue());
                }
                out.putNextEntry(n);
                out.write(data);
                out.closeEntry();
            }
        }
        if (renamed > 0) Files.move(tmp, apk, StandardCopyOption.REPLACE_EXISTING);
        else Files.delete(tmp);
        System.out.println("FixAssets: Corrigidos " + renamed + " caminhos no APK.");
    }
}
"@
[System.IO.File]::WriteAllText("$ScriptDir\out\FixAssets.java", $fixJava, $utf8NoBom)
& $Java "out\FixAssets.java" "out\base.apk"

Write-Host "Compilando código Java..." -ForegroundColor Yellow
$javaFiles = Get-ChildItem -Path "app\src", "out\gen" -Recurse -Filter "*.java" | Select-Object -ExpandProperty FullName
& $Javac -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AndroidJar;$BuildTools\core-lambda-stubs.jar" -classpath $AndroidJar -encoding UTF-8 -d out\classes $javaFiles
if ($LASTEXITCODE -ne 0) { throw "Falha na compilação Java!" }

Write-Host "Gerando classes.dex com D8..." -ForegroundColor Yellow
$classFiles = Get-ChildItem -Path "out\classes" -Recurse -Filter "*.class" | Select-Object -ExpandProperty FullName
& $Java -Xmx1024M -cp $D8Jar com.android.tools.r8.D8 --release --min-api 26 --lib $AndroidJar --output out $classFiles
if ($LASTEXITCODE -ne 0) { throw "Falha na geração do Dex!" }

Write-Host "Adicionando classes.dex ao APK..." -ForegroundColor Yellow
& $Jar -u -M -f out/base.apk -C out classes.dex

Write-Host "Alinhando APK com zipalign..." -ForegroundColor Yellow
& $Zipalign -f -p 4 out/base.apk out/aligned.apk

# Keystore
if (-not (Test-Path "freemytv.keystore")) {
    Write-Host "Criando chave freemytv.keystore..." -ForegroundColor Yellow
    & $Keytool -genkeypair -keystore freemytv.keystore -alias freemytv -keyalg RSA -keysize 2048 -validity 20000 -storepass freemytv -keypass freemytv -dname "CN=Free My TV"
}

Write-Host "Assinando APK com apksigner..." -ForegroundColor Yellow
& $Java -jar $ApksignerJar sign --ks freemytv.keystore --ks-pass pass:freemytv --key-pass pass:freemytv --out FreeMyTV.apk out/aligned.apk

$size = (Get-Item "FreeMyTV.apk").Length / 1MB
Write-Host "✅ APK compilado com sucesso! Tamanho: $([math]::Round($size, 2)) MB -> FreeMyTV.apk" -ForegroundColor Green
